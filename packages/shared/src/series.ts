export function searchSeriesCatalog(query: string, limit = 20): SeriesDefinition[] {
  const q = query.trim().toLowerCase();
  if (!q) return SERIES_CATALOG.slice(0, limit);

  const scored = SERIES_CATALOG.map((series) => {
    const hay = [series.id, series.title, series.shortTitle, ...series.aliases]
      .join(" ")
      .toLowerCase();
    let score = 0;
    if (series.id === q) score += 100;
    if (series.shortTitle.toLowerCase() === q) score += 80;
    if (series.aliases.some((a) => a === q)) score += 70;
    if (hay.startsWith(q)) score += 40;
    if (hay.includes(q)) score += 20;
    for (const part of q.split(/\s+/)) {
      if (hay.includes(part)) score += 5;
    }
    return { series, score };
  })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score);

  return scored.slice(0, limit).map((x) => x.series);
}

